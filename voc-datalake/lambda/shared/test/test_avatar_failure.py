"""The avatar failure record: reason, plain-words message, AWS code (shared/avatar_failure.py)."""
from __future__ import annotations

import pytest

from shared import assist_jobs
from shared.avatar_failure import (
    AVATAR_FAILURE_REASONS,
    MAX_AWS_MESSAGE_CHARS,
    AvatarGenerationFailed,
    avatar_failure,
    aws_error_code,
    aws_error_message,
    classify_avatar_error,
    failure_from_exception,
)


class ClientErrorLike(Exception):
    def __init__(self, code: str, message: str = ''):
        super().__init__(f'An error occurred ({code}): {message}')
        self.response = {'Error': {'Code': code, 'Message': message}}


class TestErrorCode:
    def test_a_client_error_answers_its_aws_code(self):
        assert aws_error_code(ClientErrorLike('ThrottlingException')) == 'ThrottlingException'

    def test_anything_else_answers_its_type_name(self):
        assert aws_error_code(RuntimeError('x')) == 'RuntimeError'

    def test_the_aws_message_is_preferred_and_capped(self):
        assert aws_error_message(ClientErrorLike('X', 'short')) == 'short'
        assert len(aws_error_message(RuntimeError('y' * 2000))) == MAX_AWS_MESSAGE_CHARS


class TestClassification:
    @pytest.mark.parametrize(('error', 'reason'), [
        (ClientErrorLike('AccessDeniedException', 'not authorized to perform bedrock:InvokeModel'), 'no_access'),
        (ClientErrorLike('ValidationException', 'aws-marketplace:Subscribe required'), 'no_access'),
        (ClientErrorLike('ResourceNotFoundException'), 'model_not_found'),
        (ClientErrorLike('ValidationException', 'This model version has reached the end of its life.'),
         'model_not_found'),
        (ClientErrorLike('ServiceQuotaExceededException'), 'throttled'),
        (ClientErrorLike('ValidationException', 'blocked by our content filters'), 'content_filtered'),
        (ClientErrorLike('ValidationException', 'output_format: not a valid value'), 'validation'),
        (ClientErrorLike('InternalServerException'), 'error'),
    ])
    def test_each_aws_answer_maps_to_one_reason(self, error, reason):
        assert classify_avatar_error(error) == reason
        assert reason in AVATAR_FAILURE_REASONS


class TestMessages:
    def test_the_access_message_matches_the_wording_the_job_shows(self):
        failure = avatar_failure('no_access', model_id='stability.stable-image-core-v1:1', region='us-west-2',
                                 error_code='AccessDeniedException')
        assert failure['message'].startswith(
            'the image model stability.stable-image-core-v1:1 is not enabled in us-west-2 for this account, '
            'or the role may not invoke it (AccessDeniedException)')

    @pytest.mark.parametrize('reason', AVATAR_FAILURE_REASONS)
    def test_every_reason_has_its_own_message(self, reason):
        failure = avatar_failure(reason, model_id='m', region='r', error_code='C')
        assert failure['reason'] == reason
        assert failure['message']
        assert '{' not in failure['message']

    def test_an_unknown_reason_reads_as_an_unexpected_error(self):
        failure = avatar_failure('nope', model_id='m', region='r', error_code='C')
        assert failure['reason'] == 'error'
        assert failure['message'].startswith('unexpected error from the image model m in r (C)')

    def test_an_upload_failure_names_the_bucket_not_the_model(self):
        failure = failure_from_exception(ClientErrorLike('AccessDenied'), model_id='m', region='r', stage='upload')
        assert failure['reason'] == 'error'
        assert failure['message'] == 'the image was generated by m but storing it in the raw data bucket failed (AccessDenied)'


class TestAssistJobShowsTheReason:
    def test_the_assist_worker_records_the_classified_message(self):
        work = assist_jobs.Work(lambda _config: {}, 'Avatar generation failed')
        error = AvatarGenerationFailed('Avatar generation failed: the image model m is not enabled in r')
        assert assist_jobs._failure_text(error, 'assist_persona_avatar', work) == str(error)
