"""A voice session's transcript, saved as a project document (7.69.00; docs/voice-personas.md → The transcript).

The projects assist twin runs it (``assist_voice_finalize``, started by End or by the starter's next read of an ended
session, shared/voice_sessions.py): it reads the session's transcript parts the relay wrote under
``scratch/voice/<session>/transcript/`` and the evidence the projects API wrote beside them, and files one
``persona_interview`` document in the project:

* **synthetic, never evidence** (TENETS.md tenet 2): the row is ``synthetic: true``, its content opens with that
  label, and only the reviews the persona cited from its own evidence pack are its lineage (``input_feedback_ids``, an
  erasure removes them as it does a focus group's: jobs/retention/lineage.py); an id outside the pack is dropped;
* **the person's turns redacted** (shared/pii_redaction.py: e-mail addresses, phone and card numbers, IBANs and the
  like), the persona's turns as it spoke them, each followed by the reviews it cited as ``[fb:<id>]``;
* **a summary and key quotes** from one model call over the transcript (data, never instructions); a key quote is
  kept only when it is in the transcript word for word, and a failed call leaves the transcript without them;
* the session's ``bedrock_usage`` line (shared/usage_meter.py), so the daily cost rollup, which reads only the voc-*
  Lambda log groups, counts Nova Sonic's tokens beside every other model's.

Then the session's scratch files go, every version (the transcript parts hold the person's words unredacted; the
evidence holds review text), and the row says ``finalized`` with the document's id. Audio was never stored.
D4: the document records its creator (the session's starter), when, and ``derivation`` (the session, the persona,
the model and voice, how long, how many reviews were cited).

**A product interview** (7.104.00, ``kind: product_interview``, shared/voice_subjects.py) is the product team speaking
for itself, so it gets no summary call and no document: the person's turns are redacted the same way, and so are the
interviewer's, labelled "AI interviewer" (it confirms in a few words what it heard, so it repeats the person's words),
and the Markdown is saved as one ``interview`` source of the Product tab
(``mode: voice``, the session's id) through shared/product_sources.py ``save_interview_source``, the one way answers
become a source; the session row keeps the source's id (``source_doc_id``). The usage line and the scratch files'
delete are the same. Its start found room among the project's sources (shared/voice_sessions.py ``mint``); a project
that filled up during the interview still gets it, past the cap (``past_the_cap``), rather than lose it, and the row
says so (``over_source_cap``, which the session's view answers): the project then holds more sources than the cap,
and refuses the next one until one is deleted.
"""
from __future__ import annotations

import dataclasses
import json
import re
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from typing import Any, Final

from shared import product_sources, usage_meter, voice_sessions, voice_subjects
