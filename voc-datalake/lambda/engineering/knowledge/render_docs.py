"""The repository's agent docs, rendered (7.52.00): the approved knowledge pack as ``docs/agents/**`` and the accepted
tenets as ``TENETS.md``, the only files the broker's ``push_approved_docs`` writes (docs/autonomous-engineering.md,
"The knowledge docs pull request").

Pure and of the standard library only (with the pure modules it imports: runtime/outputs.py, checkpoints.py and
connectors/write_policy.py), so the Agents API (an approval, a preview) and the broker (its check before it writes)
render the same bytes from the same stored records:

- **Knowledge** (``render_knowledge``): from each package's stored ``pack.json`` (``voc-kpack/1``, the approved version
  the rendering names), ``docs/agents/index.md`` (every package the overview lists, with the document of each that has
  an approved version) and one ``docs/agents/<package path>.md`` per package with one: its seven documents in the
  pack's order, each claim as stored, its citations as footnotes numbered by first use in the file. The root package
  (``.``) is ``docs/agents/repository.md``; a package whose path is ``index`` or ``repository`` (in any case) is
  ``index-package.md`` or ``repository-package.md``, so no package takes the index's or the overview's place. A
  character outside ``[A-Za-z0-9@._+-]`` in a path segment becomes ``-``; two packages that would land on one file (in
  any case: checkouts on case-insensitive file systems) are refused (``RenderError``), never merged. A claim flagged
  for review (it contradicts a person's edit) is not rendered: it was never applied.
- **Tenets** (``render_tenets``): ``TENETS.md`` from an accepted ``voc-tenets/1`` record, each tenet under its id.

Every piece of text a pack or a record holds was mined or written from repository text by a model: it is escaped as
literal Markdown (no link, image, HTML, heading or table cell can come from it), and a citation is a code span only
when it has no backtick. The same records always render the same bytes; ``rendering_digest`` is the sha256 of the
canonical ``[(path, sha256)]`` list (sorted by path, JSON without spaces), what an approval stores and what the
broker holds a write to.
"""
from __future__ import annotations

import difflib
import hashlib
import json
import re
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from typing import Any, Final

from engineering.connectors.write_policy import TENETS_PATH
from engineering.runtime.checkpoints import SHA
from engineering.runtime.outputs import NOTE_KINDS, TENETS_SCHEMA

#: The two kinds of rendering, as the docs routes and the broker name them.
KNOWLEDGE, TENETS = 'knowledge', 'tenets'
KINDS: Final = (KNOWLEDGE, TENETS)
DOCS_DIR: Final = 'docs/agents'
INDEX_PATH: Final = f'{DOCS_DIR}/index.md'
REPOSITORY_PATH: Final = f'{DOCS_DIR}/repository.md'
#: A rendering's digest as a request names it: a sha256, hex.
DIGEST: Final = re.compile(r'[0-9a-f]{64}\Z')
#: The root package's path (knowledge/workspaces.py ``ROOT``, which a test holds equal), here so this module imports
#: no store.
ROOT: Final = '.'
#: A stored pack's schema (knowledge/reduce.py writes and reads it from here).
PACK_SCHEMA: Final = 'voc-kpack/1'
#: Each document's heading (knowledge/reduce.py renders the pack's own documents with them).
TITLES: Final = {'architecture': 'Architecture', 'convention': 'Conventions', 'review-guide': 'Review guide',
                 'test-strategy': 'Test strategy', 'ci': 'CI and gates', 'glossary': 'Glossary',
                 'how-we-work': 'How we work'}
#: The package paths that would take the index's or the overview's place, and what they are renamed to.
_RESERVED: Final = {'index': 'index-package', 'repository': 'repository-package'}
_SAFE: Final = re.compile(r'[A-Za-z0-9@._+-]')
#: The characters escaped in repository text (knowledge/reduce.py's documents escape the same).
ESCAPED: Final = frozenset('\\`*_[]<>!|#~&')
#: The most packages one rendering holds (knowledge/workspaces.py ``MAX_PACKAGES``, and the root).
MAX_PACKAGES: Final = 2_001
GENERATED: Final = ('> Generated by the Voice of the Customer data lake from the approved knowledge pack. Do not edit '
                    'this file: edit the pack under Agent orchestration, and its next approved version replaces it.')
TENETS_GENERATED: Final = ('> The tenets an administrator accepted (version {version}) from a draft by the Voice of '
                           'the Customer data lake\'s agents. A triage cites them by id. Do not edit this file by '
                           'hand: the next accepted version replaces it.')


class RenderError(ValueError):
    """A record that cannot be rendered as it is (off its schema, or two packages on one file)."""


@dataclass(frozen=True)
class RenderedFile:
    path: str
    content: bytes

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.content).hexdigest()

    def view(self) -> dict[str, Any]:
        return {'path': self.path, 'sha256': self.sha256, 'bytes': len(self.content)}


@dataclass(frozen=True)
class Rendering:
    """What a kind renders to: its files, in the order they are listed (the index first)."""

    kind: str
    files: tuple[RenderedFile, ...]

    @property
    def digest(self) -> str:
        return rendering_digest(self.files)

    def paths(self) -> tuple[str, ...]:
        return tuple(file.path for file in self.files)

    def manifest(self) -> list[dict[str, Any]]:
        return [file.view() for file in self.files]


def rendering_digest(files: Iterable[RenderedFile]) -> str:
    """The sha256 (hex) of the canonical ``[(path, sha256)]`` list: sorted by path, JSON with no spaces."""
    canonical = json.dumps(sorted([file.path, file.sha256] for file in files), separators=(',', ':'))
    return hashlib.sha256(canonical.encode()).hexdigest()


def escape(text: str) -> str:
    """Repository text as literal Markdown on one line: no link, image, HTML, heading or table cell comes from it."""
    one_line = ' '.join(str(text).split())
    return ''.join(f'\\{ch}' if ch in ESCAPED else ch for ch in one_line)


def _code(text: str) -> str:
    return f'`{text}`' if text and '`' not in text and '\n' not in text else escape(text)


def doc_path(package: str) -> str:
    """The file a package's document is rendered to (the module's doc)."""
    if package == ROOT:
        return REPOSITORY_PATH
    parts = package.split('/')
    if not package or len(package) > 300 or any(part in ('', '.', '..') for part in parts):
        raise RenderError(f'not a package path: {package[:80]!r}')
    safe = '/'.join(''.join(ch if _SAFE.fullmatch(ch) else '-' for ch in part) for part in parts)
    renamed = _RESERVED.get(safe.casefold())
    return f'{DOCS_DIR}/{safe if renamed is None else f"{safe}-package"}.md'


def _footnote(citation: str) -> str:
    if citation.startswith('https://') and '>' not in citation and ' ' not in citation:
        return f'<{citation}>'
    if SHA.fullmatch(citation):
        return f'commit {_code(citation)}'
    return _code(citation)


def _claims(raw: object, numbers: dict[str, int]) -> list[str]:
    lines: list[str] = []
    for note in raw if isinstance(raw, list) else []:
        if not isinstance(note, Mapping) or not isinstance(note.get('claim'), str) or not note['claim'].strip():
            continue
        citations = [str(c) for c in note.get('citations') or [] if isinstance(c, str) and c]
        marks = ''.join(f'[^{numbers.setdefault(c, len(numbers) + 1)}]' for c in citations)
        subject = note.get('subject')
        about = f'**{escape(subject)}**: ' if isinstance(subject, str) and subject.strip() else ''
        edited = ' (edited by a person)' if note.get('author') else ''
        lines.append(f'- {about}{escape(note["claim"])}{marks}{edited}')
    return lines


def _package_table(listed: object) -> list[str]:
    rows = ['| Package | Name | Kinds | Owners |', '|---|---|---|---|']
    for item in listed if isinstance(listed, list) else []:
        if not isinstance(item, Mapping) or not isinstance(item.get('path'), str):
            continue
        kinds = ', '.join(escape(k) for k in item.get('kinds') or [] if isinstance(k, str)) or 'none'
        owners = escape(' '.join(o for o in item.get('owners') or [] if isinstance(o, str))) or 'none'
        rows.append(f'| {_code(item["path"])} | {escape(str(item.get("name", "")))} | {kinds} | {owners} |')
    return [*rows, '']


def _checked_pack(package: str, pack: Mapping[str, Any]) -> Mapping[str, Any]:
    documents = pack.get('documents')
    if pack.get('schema') != PACK_SCHEMA or pack.get('package') != package or not isinstance(documents, Mapping):
        raise RenderError(f'the stored pack of {package[:80]!r} is not a {PACK_SCHEMA} document of that package')
    return documents


def _name(package: str) -> str:
    return 'the repository' if package == ROOT else _code(package)


def _package_doc(package: str, pack: Mapping[str, Any], version: int) -> bytes:
    documents = _checked_pack(package, pack)
    lines = [f'# Agent knowledge: {_name(package)}', '', GENERATED, '',
             f'Approved knowledge pack version {version}.', '']
    numbers: dict[str, int] = {}
    for kind in NOTE_KINDS:
        lines += [f'## {TITLES[kind]}', '']
        if kind == 'architecture' and package == ROOT and pack.get('packages'):
            lines += ['### Packages', '', *_package_table(pack.get('packages'))]
        claims = _claims(documents.get(kind), numbers)
        lines += [*(claims or ['Nothing is approved about this yet.']), '']
    if numbers:
        lines += [f'[^{n}]: {_footnote(c)}' for c, n in numbers.items()] + ['']
    return '\n'.join(lines).rstrip('\n').encode() + b'\n'


def _listed_packages(packs: Mapping[str, Mapping[str, Any]]) -> list[str]:
    root = packs.get(ROOT)
    listed = root.get('packages') if root is not None else None
    named = {str(item['path']) for item in listed if isinstance(item, Mapping) and isinstance(item.get('path'), str)} \
        if isinstance(listed, list) else set()
    return [ROOT, *sorted((named | set(packs)) - {ROOT})]


def _index(packages: Sequence[str], packs: Mapping[str, Mapping[str, Any]], versions: Mapping[str, int]) -> bytes:
    lines = ['# Agent knowledge', '', GENERATED, '',
             'What the autonomous engineering agents know about this repository, one document per package.', '',
             '| Package | Document | Approved version |', '|---|---|---|']
    for package in packages:
        if package in packs:
            target = doc_path(package)[len(DOCS_DIR) + 1:]
            lines.append(f'| {_name(package)} | [{escape(target)}]({target}) | {int(versions.get(package, 0))} |')
        else:
            lines.append(f'| {_name(package)} | not approved yet | |')
    return '\n'.join(lines).encode() + b'\n'


def render_knowledge(packs: Mapping[str, Mapping[str, Any]], versions: Mapping[str, int]) -> Rendering:
    """``docs/agents/**`` from each package's stored approved pack (``packs``: package path -> its ``pack.json``),
    ``versions`` the approved version of each. No pack at all renders nothing but the index."""
    if len(packs) > MAX_PACKAGES:
        raise RenderError(f'a rendering holds at most {MAX_PACKAGES} packages')
    packages = _listed_packages(packs)
    files = [RenderedFile(INDEX_PATH, _index(packages, packs, versions))]
    seen: dict[str, str] = {INDEX_PATH.casefold(): INDEX_PATH}
    for package in packages:
        if package not in packs:
            continue
        path = doc_path(package)
        if path.casefold() in seen:
            raise RenderError(f'two packages render to {path} (rename one, or approve the docs by hand)')
        seen[path.casefold()] = path
        files.append(RenderedFile(path, _package_doc(package, packs[package], int(versions.get(package, 0)))))
    return Rendering(KNOWLEDGE, tuple(files))


def render_tenets(record: Mapping[str, Any], version: int) -> Rendering:
    """``TENETS.md`` from an accepted ``voc-tenets/1`` record (``version``: the accepted version's number)."""
    tenets = record.get('tenets')
    if record.get('schema') != TENETS_SCHEMA or not isinstance(tenets, list) or not tenets:
        raise RenderError(f'the accepted record is not a {TENETS_SCHEMA} record with tenets')
    lines = ['# Tenets', '', TENETS_GENERATED.format(version=int(version)), '']
    summary = record.get('summary')
    if isinstance(summary, str) and summary.strip():
        lines += [escape(summary), '']
    for tenet in tenets:
        if not isinstance(tenet, Mapping):
            raise RenderError('a tenet is an object')
        lines += [f'## {escape(str(tenet.get("id", "")))}: {escape(str(tenet.get("title", "")))}', '',
                  escape(str(tenet.get('statement', ''))), '']
        rationale = tenet.get('rationale')
        if isinstance(rationale, str) and rationale.strip():
            lines += [f'Why: {escape(rationale)}', '']
        citations = [_footnote(str(c)) for c in tenet.get('citations') or [] if isinstance(c, str) and c]
        if citations:
            lines += [f'Sources: {", ".join(citations)}.', '']
    return Rendering(TENETS, (RenderedFile(TENETS_PATH, '\n'.join(lines).rstrip('\n').encode() + b'\n'),))


def patch(rendering: Rendering) -> str:
    """The rendering as a git patch that adds each file (``git apply``): what a Human-driven administrator applies by
    hand. ``git apply`` refuses a file the repository has already (a hand-written TENETS.md): that one is replaced
    with the patch's lines by hand."""
    parts: list[str] = []
    for file in rendering.files:
        text = file.content.decode()
        diff = difflib.unified_diff([], text.splitlines(keepends=True), '/dev/null', f'b/{file.path}', lineterm='\n')
        parts.append(f'diff --git a/{file.path} b/{file.path}\nnew file mode 100644\n' + ''.join(diff))
    return ''.join(parts)
